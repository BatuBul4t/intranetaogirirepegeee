begin;

create table if not exists public.temporary_chat_messages (
    id bigint generated by default as identity primary key,
    chat_name text not null check (char_length(chat_name) between 1 and 32),
    content text not null check (char_length(content) between 1 and 800),
    created_at timestamptz not null default now(),
    expires_at timestamptz not null default (now() + interval '30 minutes')
);

create index if not exists temporary_chat_messages_created_idx
on public.temporary_chat_messages(created_at desc);

create index if not exists temporary_chat_messages_expires_idx
on public.temporary_chat_messages(expires_at);

alter table public.temporary_chat_messages enable row level security;

drop policy if exists "public read live chat messages" on public.temporary_chat_messages;
create policy "public read live chat messages"
on public.temporary_chat_messages for select
to anon, authenticated
using (expires_at > now());

drop policy if exists "public create live chat messages" on public.temporary_chat_messages;
create policy "public create live chat messages"
on public.temporary_chat_messages for insert
to anon, authenticated
with check (
    char_length(chat_name) between 1 and 32
    and char_length(content) between 1 and 800
    and expires_at > now()
    and expires_at <= now() + interval '31 minutes'
);

create or replace function public.cleanup_expired_temporary_chat()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    delete from public.temporary_chat_messages
    where expires_at <= now();
    return null;
end;
$$;

drop trigger if exists trg_cleanup_expired_temporary_chat on public.temporary_chat_messages;
create trigger trg_cleanup_expired_temporary_chat
after insert on public.temporary_chat_messages
for each statement execute function public.cleanup_expired_temporary_chat();

alter table public.temporary_chat_messages replica identity full;

do $$
begin
    if not exists (
        select 1 from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'temporary_chat_messages'
    ) then
        alter publication supabase_realtime add table public.temporary_chat_messages;
    end if;
end $$;

create table if not exists public.admin_users (
    user_id uuid primary key references auth.users(id) on delete cascade,
    username text not null unique check (char_length(username) between 1 and 40),
    created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;

drop policy if exists "admin can read own role" on public.admin_users;
create policy "admin can read own role"
on public.admin_users for select
to authenticated
using (user_id = auth.uid());

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.admin_users
        where user_id = auth.uid()
    );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

drop policy if exists "admin read all chat messages" on public.temporary_chat_messages;
create policy "admin read all chat messages"
on public.temporary_chat_messages for select
to authenticated
using (public.is_admin());

drop policy if exists "admin delete chat messages" on public.temporary_chat_messages;
create policy "admin delete chat messages"
on public.temporary_chat_messages for delete
to authenticated
using (public.is_admin());

drop policy if exists "admin delete forum threads" on public.forum_threads;
create policy "admin delete forum threads"
on public.forum_threads for delete
to authenticated
using (public.is_admin());

drop policy if exists "admin delete forum posts" on public.forum_posts;
create policy "admin delete forum posts"
on public.forum_posts for delete
to authenticated
using (public.is_admin());

drop policy if exists "admin delete article comments" on public.article_comments;
create policy "admin delete article comments"
on public.article_comments for delete
to authenticated
using (public.is_admin());

drop policy if exists "admin delete community articles" on public.community_articles;
create policy "admin delete community articles"
on public.community_articles for delete
to authenticated
using (public.is_admin());

create or replace function public.sync_forum_thread_after_post_delete()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    update public.forum_threads
    set reply_count = (
        select count(*)::integer
        from public.forum_posts
        where thread_id = old.thread_id
    ),
    last_post_at = coalesce(
        (
            select max(created_at)
            from public.forum_posts
            where thread_id = old.thread_id
        ),
        created_at
    )
    where id = old.thread_id;
    return old;
end;
$$;

drop trigger if exists trg_sync_forum_thread_after_post_delete on public.forum_posts;
create trigger trg_sync_forum_thread_after_post_delete
after delete on public.forum_posts
for each row execute function public.sync_forum_thread_after_post_delete();

grant select, insert on public.temporary_chat_messages to anon, authenticated;
grant delete on public.temporary_chat_messages to authenticated;
grant select on public.admin_users to authenticated;
grant delete on public.forum_threads, public.forum_posts, public.article_comments, public.community_articles to authenticated;
grant usage, select on sequence public.temporary_chat_messages_id_seq to anon, authenticated;

commit;
