begin;

create table if not exists public.forum_threads (
    id bigint generated by default as identity primary key,
    board text not null check (board in ('general','ccg','occult','ward20','tech','games','anime','books')),
    title text not null check (char_length(title) between 1 and 140),
    anon_id text not null check (char_length(anon_id) between 3 and 40),
    created_at timestamptz not null default now(),
    last_post_at timestamptz not null default now(),
    reply_count integer not null default 0 check (reply_count >= 0)
);

create table if not exists public.forum_posts (
    id bigint generated by default as identity primary key,
    thread_id bigint not null references public.forum_threads(id) on delete cascade,
    anon_id text not null check (char_length(anon_id) between 3 and 40),
    content text not null check (char_length(content) between 1 and 4000),
    created_at timestamptz not null default now()
);

create table if not exists public.article_comments (
    id bigint generated by default as identity primary key,
    article_id text not null check (char_length(article_id) between 1 and 80),
    anon_id text not null check (char_length(anon_id) between 3 and 40),
    content text not null check (char_length(content) between 1 and 2500),
    created_at timestamptz not null default now()
);

create index if not exists forum_threads_board_last_idx
on public.forum_threads(board, last_post_at desc);

create index if not exists forum_posts_thread_idx
on public.forum_posts(thread_id, created_at);

create index if not exists article_comments_article_idx
on public.article_comments(article_id, created_at);

alter table public.forum_threads enable row level security;
alter table public.forum_posts enable row level security;
alter table public.article_comments enable row level security;

drop policy if exists "public read forum threads" on public.forum_threads;
create policy "public read forum threads"
on public.forum_threads for select
to anon, authenticated
using (true);

drop policy if exists "public create forum threads" on public.forum_threads;
create policy "public create forum threads"
on public.forum_threads for insert
to anon, authenticated
with check (
    char_length(title) between 1 and 140
    and char_length(anon_id) between 3 and 40
    and reply_count = 0
);

drop policy if exists "public read forum posts" on public.forum_posts;
create policy "public read forum posts"
on public.forum_posts for select
to anon, authenticated
using (true);

drop policy if exists "public create forum posts" on public.forum_posts;
create policy "public create forum posts"
on public.forum_posts for insert
to anon, authenticated
with check (
    char_length(content) between 1 and 4000
    and char_length(anon_id) between 3 and 40
);

drop policy if exists "public read article comments" on public.article_comments;
create policy "public read article comments"
on public.article_comments for select
to anon, authenticated
using (true);

drop policy if exists "public create article comments" on public.article_comments;
create policy "public create article comments"
on public.article_comments for insert
to anon, authenticated
with check (
    char_length(content) between 1 and 2500
    and char_length(anon_id) between 3 and 40
);

create or replace function public.bump_forum_thread()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    update public.forum_threads
    set last_post_at = new.created_at,
        reply_count = (
            select count(*)::integer
            from public.forum_posts
            where thread_id = new.thread_id
        )
    where id = new.thread_id;
    return new;
end;
$$;

drop trigger if exists trg_bump_forum_thread on public.forum_posts;
create trigger trg_bump_forum_thread
after insert on public.forum_posts
for each row execute function public.bump_forum_thread();

alter table public.forum_threads replica identity full;
alter table public.forum_posts replica identity full;
alter table public.article_comments replica identity full;

do $$
begin
    if not exists (
        select 1 from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'forum_threads'
    ) then
        alter publication supabase_realtime add table public.forum_threads;
    end if;

    if not exists (
        select 1 from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'forum_posts'
    ) then
        alter publication supabase_realtime add table public.forum_posts;
    end if;

    if not exists (
        select 1 from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'article_comments'
    ) then
        alter publication supabase_realtime add table public.article_comments;
    end if;
end $$;


create table if not exists public.community_articles (
    id bigint generated by default as identity primary key,
    title text not null check (char_length(title) between 1 and 180),
    category text not null default 'Comunidade' check (char_length(category) between 1 and 80),
    source_name text not null default 'Arquivo Comunitário' check (char_length(source_name) between 1 and 120),
    date_label text not null default '2001' check (char_length(date_label) between 1 and 40),
    summary text not null check (char_length(summary) between 1 and 600),
    body text not null check (char_length(body) between 1 and 12000),
    tags text[] not null default '{}',
    anon_id text not null check (char_length(anon_id) between 3 and 40),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists community_articles_created_idx
on public.community_articles(created_at desc);

create index if not exists community_articles_category_idx
on public.community_articles(category);

alter table public.community_articles enable row level security;

drop policy if exists "public read community articles" on public.community_articles;
create policy "public read community articles"
on public.community_articles for select
to anon, authenticated
using (true);

drop policy if exists "public create community articles" on public.community_articles;
create policy "public create community articles"
on public.community_articles for insert
to anon, authenticated
with check (
    char_length(title) between 1 and 180
    and char_length(summary) between 1 and 600
    and char_length(body) between 1 and 12000
    and char_length(anon_id) between 3 and 40
);

alter table public.community_articles replica identity full;

do $$
begin
    if not exists (
        select 1 from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'community_articles'
    ) then
        alter publication supabase_realtime add table public.community_articles;
    end if;
end $$;

commit;
